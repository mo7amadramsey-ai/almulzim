// Fetches the video's own published captions (no audio is downloaded). Videos without captions need pasted text.
import 'package:youtube_explode_dart/youtube_explode_dart.dart';
import 'notebook_models.dart';

class Transcript {
  final String videoId, title, lang;
  final bool auto;
  final List<String> lines; // "[mm:ss] text", cues merged into ~20 s groups
  Transcript(this.videoId, this.title, this.lang, this.auto, this.lines);
}

Future<Transcript> fetchTranscript(String url) async {
  final yt = YoutubeExplode();
  try {
    final VideoId id;
    try {
      id = VideoId(url.trim());
    } catch (_) {
      throw 'رابط يوتيوب غير صالح';
    }
    final video = await yt.videos.get(id);
    final manifest = await yt.videos.closedCaptions.getManifest(id);
    final tracks = manifest.tracks.toList();
    if (tracks.isEmpty) {
      throw 'لا توجد ترجمة نصية لهذا الفيديو. الصق نص المحاضرة بدلاً من ذلك.';
    }
    int score(dynamic t) =>
        (t.isAutoGenerated == true ? 0 : 10) + (t.language.code.toString().startsWith('ar') ? 2 : (t.language.code.toString().startsWith('en') ? 1 : 0));
    tracks.sort((a, b) => score(b).compareTo(score(a)));
    final pick = tracks.first;
    final track = await yt.videos.closedCaptions.get(pick);
    final lines = <String>[];
    final cur = StringBuffer();
    var curStart = 0;
    for (final c in track.captions) {
      final sec = c.offset.inSeconds;
      if (cur.isEmpty) curStart = sec;
      cur.write('${c.text.replaceAll('\n', ' ').trim()} ');
      if (sec - curStart >= 20) {
        lines.add('[${fmtTs(curStart)}] ${cur.toString().trim()}');
        cur.clear();
      }
    }
    if (cur.isNotEmpty) lines.add('[${fmtTs(curStart)}] ${cur.toString().trim()}');
    if (lines.isEmpty) throw 'الترجمة النصية فارغة. الصق نص المحاضرة بدلاً من ذلك.';
    return Transcript(id.value, video.title, pick.language.code.toString(), pick.isAutoGenerated, lines);
  } on String {
    rethrow;
  } catch (e) {
    throw 'تعذّر جلب الترجمة النصية: تأكد من الإنترنت أو الصق نص المحاضرة.';
  } finally {
    yt.close();
  }
}

/// Parses "[mm:ss]" / "[h:mm:ss]" prefixes back to seconds (null if absent)
int? lineSeconds(String l) {
  final m = RegExp(r'^\[(?:(\d+):)?(\d{1,2}):(\d{2})\]').firstMatch(l);
  if (m == null) return null;
  return (int.tryParse(m.group(1) ?? '0') ?? 0) * 3600 + int.parse(m.group(2)!) * 60 + int.parse(m.group(3)!);
}
